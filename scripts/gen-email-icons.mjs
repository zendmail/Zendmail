// One-off generator: copies the SVG drawing data of the Lucide icons used by the email builder into
// src/lib/email-builder/icon-data.ts, so the image route can draw them without react-dom/server.
// Run: node scripts/gen-email-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const MAP = {
  check: "check", bolt: "zap", shield: "shield-check", heart: "heart", leaf: "leaf", truck: "truck", gift: "gift",
  clock: "clock", sparkles: "sparkles", users: "users", chart: "chart-column", mail: "mail", "map-pin": "map-pin",
  calendar: "calendar", lock: "lock", droplet: "droplet", award: "award", refresh: "refresh-cw", message: "message-circle",
  package: "package", tag: "tag", percent: "percent", trophy: "trophy", target: "target", smile: "smile", phone: "phone",
  star: "star", cart: "shopping-cart", file: "file-text", settings: "settings", rocket: "rocket", flask: "flask-conical",
  home: "house", brain: "brain", sun: "sun", moon: "moon", key: "key", globe: "globe", music: "music", x: "x",
};

const out = {};
for (const [name, file] of Object.entries(MAP)) {
  let src = readFileSync(`node_modules/lucide-react/dist/esm/icons/${file}.mjs`, "utf8");
  // Some icons are aliases that re-export another icon file; follow them.
  for (let hops = 0; hops < 3; hops++) {
    const alias = src.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
    if (!alias) break;
    src = readFileSync(`node_modules/lucide-react/dist/esm/icons/${alias[1]}.mjs`, "utf8");
  }
  const match = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst /);
  if (!match) throw new Error(`Could not parse ${file}`);
  const nodes = new Function(`return ${match[1]}`)();
  out[name] = nodes.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key"))]);
}

const body = `// GENERATED by scripts/gen-email-icons.mjs from lucide-react (ISC licence). Do not edit by hand.
export type IconNode = [string, Record<string, string | number>][];
export const ICON_NODES: Record<string, IconNode> = ${JSON.stringify(out)};
`;
writeFileSync("src/lib/email-builder/icon-data.ts", body);
console.log("wrote", Object.keys(out).length, "icons,", body.length, "bytes");
